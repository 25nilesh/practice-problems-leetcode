class Solution {
public:
    long long countCommas(long long n) {

        if (n < 1000)
            return 0;

        if (n < 1000000)
            return n - 1000 + 1;

        else if (n < 1000000000)
            return (n - 1000000 + 1) * 2
                 + (1000000 - 1000);

        else if (n < 1000000000000LL)
            return (n - 1000000000 + 1) * 3
                 + (1000000000 - 1000000) * 2
                 + (1000000 - 1000);

        else if (n < 1000000000000000LL)
            return (n - 1000000000000LL + 1) * 4
                 + (1000000000000LL - 1000000000) * 3
                 + (1000000000 - 1000000) * 2
                 + (1000000 - 1000);

        else
            return (n - 1000000000000000LL + 1) * 5
                 + (1000000000000000LL - 1000000000000LL) * 4
                 + (1000000000000LL - 1000000000) * 3
                 + (1000000000 - 1000000) * 2
                 + (1000000 - 1000);
    }
};